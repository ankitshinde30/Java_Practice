public class Swap {
    public static void main(String[] args) {
        int num1=23;
        int num2=45;
        int temp;  //used the 3rd Variable to swap
        temp =num1;
        num1=num2;
        num2=temp;
        System.out.println("swaped num1 from 23 to "+ num1);
        System.out.println("swaped num2 from 45 to "+ num2);
    }
}
